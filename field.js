/* Field — production design module. Home and research index templates,
   article/lab artwork via static SVGs generated by scripts/generate-field-art.mjs,
   and horizontal rail wiring with per-render listener cleanup. */

const Field = (() => {
  const esc = s => String(s).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  const kinds = {mindcuber:'lattice', abliteration:'manifold', nvfp4:'signal', haskell:'surface'};

  function art(kind, tone='dark', {eager=false, alt=''}={}){
    return `<img src="/assets/field-${kind}-${tone}.svg" width="1000" height="700" alt="${esc(alt)}" ${eager?'fetchpriority="high" loading="eager"':'loading="lazy"'} decoding="async">`;
  }

  function card(a, i=0){
    const tone = i%2 ? 'light' : 'dark';
    return `<a class="field-card card-${tone}" href="#article/${esc(a.id)}"><span class="field-card-topic">${esc(a.tag)}</span><h3>${esc(a.title)}</h3><span class="field-card-art">${art(kinds[a.id]||'surface',tone)}</span><span class="field-card-bottom"><span class="field-card-action">Read the note ↗</span><small>${esc(a.read.toLowerCase())} read</small></span></a>`;
  }

  function railControls(id){
    return `<div class="rail-controls"><button type="button" data-rail="${id}" data-step="-1" aria-label="Previous research cards">←</button><button type="button" data-rail="${id}" data-step="1" aria-label="Next research cards">→</button></div>`;
  }

  function home(articles){
    const labCard = `<a class="field-card card-light" href="#lab"><span class="field-card-topic">The lab</span><h3>Try an experiment</h3><span class="field-card-art">${art('surface','light')}</span><span class="field-card-bottom"><span class="field-card-action">Two experiments ↗</span><small>In your browser</small></span></a>`;
    return `<section class="field-hero">
  <div class="field-hero-art" aria-hidden="true">${art('stream','dark',{eager:true})}</div>
  <div class="field-hero-shade" aria-hidden="true"></div>
  <div class="field-hero-copy">
    <p class="eyebrow">Independent AI research</p>
    <h1>Inside the room</h1>
    <p>Taking open models apart. Following the mathematics.<br>Finding out what’s really going on inside.</p>
    <a class="pill light" href="#research">Explore the research <span>↗</span></a>
  </div>
  <div class="field-caption"><span>Chinese Room · Joe Dowling</span><span>The residual stream / Thirty-four layers, one river</span><a href="#research" data-scroll-target="field-research">Scroll to discover ↓</a></div>
</section>
<section class="field-research section-dark" id="field-research">
  <div class="section-head"><div><p class="eyebrow">Follow a question</p><h2>Four ways into the room.</h2></div><div class="section-head-side"><a class="text-link" href="#research">Full research index ↗</a>${railControls('field-rail')}</div></div>
  <div class="card-rail field-rail" id="field-rail" tabindex="0" aria-label="Research projects">${articles.map(card).join('')}${labCard}</div>
  <p class="rail-note">Scroll to explore ↔</p>
</section>
<section class="field-experiments section-dark" id="field-experiments">
  <div class="field-exp-intro"><p class="eyebrow">Make the ideas tangible</p><h2>A little less abstract.</h2><p>Turn a cube. Round a weight.<br>Explore two experiments in your browser.</p></div>
  <div class="field-exp-links">
    <a class="experiment-link" href="#lab/mindcuber"><span class="exp-no">01</span> <span class="exp-name">Mindcuber</span> <span class="exp-arrow">↗</span></a>
    <a class="experiment-link" href="#lab/quantization"><span class="exp-no">02</span> <span class="exp-name">Quantization</span> <span class="exp-arrow">↗</span></a>
  </div>
</section>`;
  }

  function research(articles){
    const tags=['ALL',...new Set(articles.map(a=>a.tag))];
    return `<section class="page research-page">
  <p class="eyebrow">Research / The notebook</p>
  <h1 class="page-title">Follow a question.</h1>
  <p class="page-intro">Long-form write-ups of experiments on a DGX Spark. Theory first, kept readable, with the maths where it earns its place.</p>
  <div class="filters" role="group" aria-label="Filter research">${tags.map((x,i)=>`<button class="filter${i===0?' active':''}" data-filter="${esc(x)}" aria-pressed="${i===0}">${esc(x)}${i===0?` · ${articles.length}`:''}</button>`).join('')}</div>
  <div class="field-grid" id="article-list">${articles.map(card).join('')}</div>
  <p id="research-count" class="research-count" role="status">${articles.length} research notes</p>
</section>`;
  }

  let cleanup = () => {};

  function wire(){
    cleanup();
    const controller = new AbortController();
    const {signal} = controller;
    cleanup = () => controller.abort();
    const app = document.querySelector('#app');
    const reduced = () => matchMedia('(prefers-reduced-motion: reduce)').matches;

    const railStep = rail => {
      const cardEl=[...rail.children].find(c=>!c.hidden);
      const gap=parseFloat(getComputedStyle(rail).columnGap||getComputedStyle(rail).gap)||20;
      return cardEl ? cardEl.offsetWidth+gap : rail.clientWidth*.8;
    };
    const updateButtons = rail => {
      const prev=document.querySelector(`[data-rail="${rail.id}"][data-step="-1"]`);
      const next=document.querySelector(`[data-rail="${rail.id}"][data-step="1"]`);
      const max=rail.scrollWidth-rail.clientWidth;
      if(prev)prev.disabled = rail.scrollLeft<=2 || max<=2;
      if(next)next.disabled = rail.scrollLeft>=max-2 || max<=2;
    };

    app.querySelectorAll('[data-rail]').forEach(btn=>{
      btn.addEventListener('click',()=>{
        const rail=document.getElementById(btn.dataset.rail);
        if(!rail)return;
        rail.scrollBy({left:Number(btn.dataset.step)*railStep(rail),behavior:reduced()?'auto':'smooth'});
      },{signal});
    });
    app.querySelectorAll('.card-rail').forEach(rail=>{
      rail.addEventListener('scroll',()=>updateButtons(rail),{passive:true,signal});
      rail.addEventListener('keydown',e=>{
        if(e.target!==rail)return;
        if(e.key==='ArrowLeft'||e.key==='ArrowRight'){e.preventDefault();rail.scrollBy({left:(e.key==='ArrowRight'?1:-1)*railStep(rail),behavior:reduced()?'auto':'smooth'});}
        if(e.key==='Home'){e.preventDefault();rail.scrollTo({left:0,behavior:reduced()?'auto':'smooth'});}
        if(e.key==='End'){e.preventDefault();rail.scrollTo({left:rail.scrollWidth,behavior:reduced()?'auto':'smooth'});}
      },{signal});
      updateButtons(rail);
    });
    addEventListener('resize',()=>app.querySelectorAll('.card-rail').forEach(updateButtons),{signal});

    app.querySelectorAll('[data-scroll-target]').forEach(a=>{
      a.addEventListener('click',e=>{
        e.preventDefault();
        document.getElementById(a.dataset.scrollTarget)?.scrollIntoView({behavior:reduced()?'auto':'smooth'});
      },{signal});
    });

    app.querySelectorAll('.cube-glyph').forEach(el=>{el.innerHTML=art('lattice','dark');});
    app.querySelectorAll('.quant-glyph').forEach(el=>{el.innerHTML=art('signal','dark');});
  }

  return {art, card, home, research, wire};
})();
